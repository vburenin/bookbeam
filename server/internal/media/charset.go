package media

import "unicode/utf8"

// Tag text that is not UTF-16 is often not what its label claims. ID3
// "ISO-8859-1" frames, ID3v1 tags, RIFF INFO chunks and even fields labelled
// UTF-8 routinely carry whatever single-byte code page the tagging PC used:
// Windows-1252 for western languages and Windows-1251 for Russian, Ukrainian,
// Belarusian, Bulgarian and Serbian rips. legacyText tells these apart.

// legacyText decodes text of unknown single-byte origin to UTF-8. Pure ASCII
// and valid UTF-8 are returned as is (real Windows-125x text with non-ASCII
// letters almost never forms valid UTF-8). Otherwise the bytes are decoded as
// Windows-1251 when they look Cyrillic, else as Windows-1252, the superset of
// ISO-8859-1 that browsers also use for "Latin-1".
func legacyText(b []byte) string {
	if utf8.Valid(b) {
		return string(b)
	}
	table := &cp1252
	if looksCP1251(b) {
		table = &cp1251
	}
	r := make([]rune, len(b))
	for i, c := range b {
		if c < 0x80 {
			r[i] = rune(c)
		} else {
			r[i] = table[c-0x80]
		}
	}
	return string(r)
}

// DecodeName converts a file or folder name to valid UTF-8 for display.
// Names copied from old Windows archives can hold raw Windows-1251/1252
// bytes; those are decoded like tag text. Valid UTF-8 is returned unchanged.
func DecodeName(s string) string {
	if utf8.ValidString(s) {
		return s
	}
	return legacyText([]byte(s))
}

// looksCP1251 reports whether 8-bit text is more plausibly Windows-1251
// Cyrillic than Windows-1252 Latin. The two differ in how letters form
// words: western languages mix a few accented letters into words of ASCII
// letters ("Müller", "Informação"), while in Cyrillic text whole words are
// made of high bytes ("Ìàñòåð" is "Мастер" misread as Latin). Words are
// voted on that basis; a string with Cyrillic-looking letters but no ASCII
// letters at all (a single "Я") also counts as Cyrillic.
func looksCP1251(b []byte) bool {
	var cyrillic, latin, high, ascii int
	for i := 0; i < len(b); {
		if !isLetterByte(b[i]) {
			i++
			continue
		}
		var wordHigh, wordASCII int
		for ; i < len(b) && isLetterByte(b[i]); i++ {
			if b[i] >= 0x80 {
				wordHigh++
			} else {
				wordASCII++
			}
		}
		high += wordHigh
		ascii += wordASCII
		switch {
		case wordHigh >= 2 && wordASCII == 0:
			cyrillic++
		case wordHigh > 0 && wordASCII > 0:
			latin++
		}
	}
	if cyrillic != latin {
		return cyrillic > latin
	}
	return high > 0 && ascii == 0
}

// isLetterByte reports whether c is an ASCII letter or a byte that is a
// letter in Windows-1251 (А–я plus Ё, Є, Ї, І, Ґ, Ў in both cases).
func isLetterByte(c byte) bool {
	switch {
	case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= 0xC0:
		return true
	}
	switch c {
	case 0xA1, 0xA2, 0xA5, 0xA8, 0xAA, 0xAF, 0xB2, 0xB3, 0xB4, 0xB8, 0xBA, 0xBF:
		return true
	}
	return false
}

